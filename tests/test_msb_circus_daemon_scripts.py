"""Tests for msb-circus daemon script generation."""

from __future__ import annotations

import base64
import subprocess
from pathlib import Path

from msb_circus.config import DaemonConfig
from msb_circus.daemons import (
    EXIT_SVSCAN_NOT_READY,
    build_install_script,
    encode_env_files,
    env_transport_var,
    log_dir,
    render_env_file,
    render_finish_script,
    render_log_run_script,
    render_run_script,
    secret_dir,
    service_dir,
)


def test_path_helpers_return_expected_paths() -> None:
    assert service_dir("web") == "/run/service/circus-daemon-web"
    assert secret_dir("web") == "/run/circus-daemons/web"
    assert log_dir("web") == "/var/log/circus-daemons/web"
    assert env_transport_var("web") == "CIRCUS_DAEMON_ENV_WEB"
    assert env_transport_var("opencode-web") == "CIRCUS_DAEMON_ENV_OPENCODE_WEB"


def test_render_env_file_returns_sorted_export_lines() -> None:
    assert (
        render_env_file({"B": "plain", "A": "x y"})
        == "# Generated by msb-circus. Do not edit.\n"
        "export A='x y'\n"
        "export B=plain\n"
    )


def test_render_env_file_rejects_invalid_keys() -> None:
    for bad in ("1BAD", "A-B"):
        try:
            render_env_file({bad: "1"})
        except ValueError as exc:
            assert "invalid environment variable name" in str(exc)
        else:
            raise AssertionError(f"expected ValueError for key {bad!r}")


def test_render_env_file_quotes_single_quote_value() -> None:
    text = render_env_file({"A": "it's"})
    proc = subprocess.run(
        ["sh", "-c", '. /dev/stdin; printf %s "$A"'],
        input=text,
        check=False,
        capture_output=True,
        text=True,
    )
    assert proc.returncode == 0
    assert proc.stdout == "it's"


def test_encode_env_files_base64_encodes_rendered_env_file() -> None:
    encoded = encode_env_files({"web": {"A": "1"}})
    assert list(encoded) == ["CIRCUS_DAEMON_ENV_WEB"]
    assert base64.b64decode(
        encoded["CIRCUS_DAEMON_ENV_WEB"]
    ).decode() == render_env_file({"A": "1"})


