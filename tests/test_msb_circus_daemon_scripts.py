def test_render_finish_script_matches_expected_text() -> None:
    assert render_finish_script("web") == (
        "#!/bin/sh\n"
        "# Stop restarting after 5 exits within 60 seconds.\n"
        '[ "$(/command/s6-svstat -o wantedup .)" = true ] || exit 0\n'
        "d=/run/circus-daemons/web\n"
        "now=$(date +%s)\n"
        '{ cat "$d/exits" 2>/dev/null; echo "$now"; } '
        '| awk -v now="$now" \'now - $1 < 60\' > "$d/exits.tmp"\n'
        'mv "$d/exits.tmp" "$d/exits"\n'
        'if [ "$(wc -l < "$d/exits")" -ge 5 ]; then\n'
        '    echo "--- circus-daemon web exited 5 times within 60 seconds; '
        'not restarting"\n'
        '    rm -f "$d/exits"\n'
        '    : > "$d/failed"\n'
        "    exit 125\n"
        "fi\n"
        "exit 0\n"
    )


