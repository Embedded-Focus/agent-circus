"""Shell script generation for user-configured daemons in the sandbox VM.

Inside the VM, s6-overlay is PID 1 and supervises every directory below
``/run/service``.  Each daemon gets a service directory
``/run/service/circus-daemon-<name>`` with a ``run`` script, a ``finish``
script, a ``timeout-kill`` file and a ``log/run`` logger.  Secrets live in
``/run/circus-daemons`` (a private tmpfs, mode 0700): the daemon's
environment file at ``<name>/env.sh``, recent exit times in ``exits``, and
a ``failed`` marker when s6 gives up restarting.  Daemon logs accumulate
under ``/var/log/circus-daemons/<name>/current`` via s6-log.
"""

from __future__ import annotations

import base64
import re
import shlex
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from .config import DaemonConfig

#: Guest path scanned by s6 for service directories.
S6_SCANDIR = "/run/service"
#: Prefix of the s6 service directory for a daemon.
SERVICE_PREFIX = "circus-daemon-"
#: Seconds between readiness probes of s6-svscan in the install script.
SVSCAN_WAIT_INTERVAL_S = 0.2
#: Number of readiness probes before the install script gives up (~20 s).
SVSCAN_WAIT_TRIES = 100
#: Install script exit code when s6-svscan does not come up in time.
EXIT_SVSCAN_NOT_READY = 5
#: Guest root of the private tmpfs holding daemon secrets.
SECRET_ROOT = "/run/circus-daemons"
#: Guest root of s6-log directories for daemons.
LOG_ROOT = "/var/log/circus-daemons"
#: The finish script stops restarting a daemon after this many exits ...
CRASH_LIMIT = 5
#: ... within this many seconds.
CRASH_WINDOW_SECONDS = 60
#: s6 sends SIGKILL when a daemon is still up this long after SIGTERM.
KILL_TIMEOUT_MS = 10000
#: Prefix of the host-side environment variable carrying the base64-encoded
#: environment file of a daemon into the guest install script.
ENV_TRANSPORT_PREFIX = "CIRCUS_DAEMON_ENV_"

_ENV_NAME_PATTERN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _q(x: str) -> str:
    """Quote a string for safe use in a POSIX shell command.

    :param x: String to quote.
    :returns: The quoted string.
    """
    return shlex.quote(x)


def service_dir(name: str) -> str:
    """Return the s6 service directory path for a daemon.

    :param name: Daemon name.
    :returns: Guest path of the service directory.
    """
    return f"{S6_SCANDIR}/{SERVICE_PREFIX}{name}"


def secret_dir(name: str) -> str:
    """Return the private tmpfs directory path for a daemon.

    :param name: Daemon name.
    :returns: Guest path of the daemon's secret directory.
    """
    return f"{SECRET_ROOT}/{name}"


def log_dir(name: str) -> str:
    """Return the s6-log directory path for a daemon.

    :param name: Daemon name.
    :returns: Guest path of the daemon's log directory.
    """
    return f"{LOG_ROOT}/{name}"


def env_transport_var(name: str) -> str:
    """Return the environment variable name carrying a daemon's env file.

    Dashes in the daemon name become underscores and the name is uppercased.

    :param name: Daemon name.
    :returns: Environment variable name, e.g. ``"opencode-web"`` maps to
        ``"CIRCUS_DAEMON_ENV_OPENCODE_WEB"``.
    """
    return ENV_TRANSPORT_PREFIX + name.upper().replace("-", "_")


def render_env_file(env: Mapping[str, str]) -> str:
    """Render a shell-sourceable environment file for a daemon.

    :param env: Mapping of environment variable names to values.
    :returns: The file content with one ``export`` line per key, keys
        sorted, every line ending with a newline.
    :raises ValueError: If a key is not a valid POSIX variable name.
    """
    for key in env:
        if not _ENV_NAME_PATTERN.fullmatch(key):
            raise ValueError(f"invalid environment variable name: {key!r}")
    lines = ["# Generated by msb-circus. Do not edit."]
    lines.extend(f"export {key}={_q(env[key])}" for key in sorted(env))
    return "\n".join(lines) + "\n"


def encode_env_files(envs: Mapping[str, Mapping[str, str]]) -> dict[str, str]:
    """Encode daemon environment files for transport into the guest.

    Each daemon's rendered environment file is base64-encoded so it can be
    shipped in a single environment variable.

    :param envs: Mapping of daemon name to its environment.
    :returns: Mapping of environment variable name (see
        :func:`env_transport_var`) to the base64-encoded file content.
    """
    return {
        env_transport_var(name): base64.b64encode(render_env_file(env).encode()).decode(
            "ascii"
        )
        for name, env in envs.items()
    }


def render_run_script(daemon: DaemonConfig, workdir: str) -> str:
    """Render the s6 ``run`` script that launches a daemon.

    The script sources the daemon's environment file, changes into the
    working directory (``daemon.workdir`` if set, else ``workdir``) and
    replaces itself with the daemon command.

    :param daemon: Daemon configuration.
    :param workdir: Directory to use when ``daemon.workdir`` is None.
    :returns: The complete ``run`` script text with a final newline.
    """
    lines = [
        "#!/command/with-contenv sh",
        "exec 2>&1",
        f'echo "--- circus-daemon {daemon.name} start $(date -Is)"',
        f". {_q(secret_dir(daemon.name) + '/env.sh')}",
        f"cd {_q(daemon.workdir or workdir)} || exit 111",
        "exec " + " ".join(_q(part) for part in daemon.command),
    ]
    return "\n".join(lines) + "\n"


def render_finish_script(name: str) -> str:
    """Render the s6 ``finish`` script that enforces the crash limit.

    The script records each exit time and stops restarting the daemon
    (and marks it failed) once it exits :data:`CRASH_LIMIT` times within
    :data:`CRASH_WINDOW_SECONDS` seconds.

    :param name: Daemon name.
    :returns: The complete ``finish`` script text with a final newline.
    """
    d = _q(secret_dir(name))
    return f"""#!/bin/sh
# Stop restarting after {CRASH_LIMIT} exits within {CRASH_WINDOW_SECONDS} seconds.
[ "$(/command/s6-svstat -o wantedup .)" = true ] || exit 0
d={d}
now=$(date +%s)
{{ cat "$d/exits" 2>/dev/null; echo "$now"; }} | awk -v now="$now" 'now - $1 < {CRASH_WINDOW_SECONDS}' > "$d/exits.tmp"
mv "$d/exits.tmp" "$d/exits"
if [ "$(wc -l < "$d/exits")" -ge {CRASH_LIMIT} ]; then
    echo "--- circus-daemon {name} exited {CRASH_LIMIT} times within {CRASH_WINDOW_SECONDS} seconds; not restarting"
    rm -f "$d/exits"
    : > "$d/failed"
    exit 125
fi
exit 0
"""


def render_log_run_script(name: str) -> str:
    """Render the s6 ``log/run`` script that logs a daemon's stdout.

    :param name: Daemon name.
    :returns: The complete logger ``run`` script text with a final newline.
    """
    logd = _q(log_dir(name))
    return f"""#!/bin/sh
mkdir -p {logd}
exec /command/s6-log -b n10 s1000000 T {logd}
"""


def build_install_script(daemons: Sequence[DaemonConfig], workdir: str) -> str:
    """Render a POSIX ``sh`` script that registers all daemons with s6.

    The script is meant to run inside the guest as root, with one
    environment variable per daemon carrying the base64-encoded
    environment file.  It first waits until s6-svscan watches the scan
    directory, because s6-overlay may still be starting it right after
    boot (exit code :data:`EXIT_SVSCAN_NOT_READY` on timeout).  It then
    installs or updates each service directory,
    marks non-autostart daemons down, removes daemons that are no longer
    configured and finally tells s6 to scan for new services.

    :param daemons: Daemons to register, in order.
    :param workdir: Directory to use when a daemon has no ``workdir``.
    :returns: The complete install script text with a final newline.
    """
    lines: list[str] = [
        "set -eu",
        "umask 077",
        "if [ ! -x /command/s6-svscanctl ]; then",
        '    echo "msb-circus daemons need s6-overlay as PID 1 in the sandbox image" >&2',
        "    exit 3",
        "fi",
        # Right after boot, s6-overlay may not have started s6-svscan yet;
        # s6-svscanctl then exits 100. A rescan request (-a) is harmless,
        # so use it as a readiness probe before touching the scan directory.
        "i=0",
        f"until /command/s6-svscanctl -a {S6_SCANDIR} 2>/dev/null; do",
        "    i=$((i + 1))",
        f'    if [ "$i" -ge {SVSCAN_WAIT_TRIES} ]; then',
        f'        echo "s6-svscan is not running on {S6_SCANDIR}" >&2',
        f"        exit {EXIT_SVSCAN_NOT_READY}",
        "    fi",
        f"    sleep {SVSCAN_WAIT_INTERVAL_S}",
        "done",
        "mkdir -p /run/circus-daemons",
        "if ! mountpoint -q /run/circus-daemons; then",
        "    mount -t tmpfs -o size=1m,mode=0700 tmpfs /run/circus-daemons",
        "fi",
        "install_file() {",
        '    printf \'%s\' "$3" > "$1.tmp"',
        '    chmod "$2" "$1.tmp"',
        '    mv "$1.tmp" "$1"',
        "}",
    ]
    for daemon in daemons:
        n = daemon.name
        s = service_dir(n)
        t = f"{S6_SCANDIR}/.{SERVICE_PREFIX}{n}.new"
        v = env_transport_var(n)
        sd = secret_dir(n)
        lines.extend(
            [
                f"# daemon {n}",
                f"mkdir -p {sd}",
                f"printf '%s' \"${{{v}}}\" | base64 -d > {sd}/env.sh",
                f"if [ -d {s} ]; then t={s}; else rm -rf {t}; t={t}; fi",
                'mkdir -p "$t/log"',
                'install_file "$t/run" 755 ' + _q(render_run_script(daemon, workdir)),
                'install_file "$t/finish" 755 ' + _q(render_finish_script(n)),
                'install_file "$t/log/run" 755 ' + _q(render_log_run_script(n)),
                'install_file "$t/timeout-kill" 644 ' + _q(str(KILL_TIMEOUT_MS) + "\n"),
            ]
        )
        if daemon.autostart:
            lines.append('rm -f "$t/down"')
        else:
            lines.append(': > "$t/down"')
        lines.append(f'if [ "$t" != {s} ]; then mv {t} {s}; fi')
    if daemons:
        names = "|".join(d.name for d in daemons)
        lines.extend(
            [
                "for d in /run/service/circus-daemon-*; do",
                '    [ -d "$d" ] || continue',
                '    case "${d##*/circus-daemon-}" in',
                f"        {names}) continue ;;",
                "    esac",
                '    /command/s6-svc -wD -T 12000 -d "$d" || true',
                '    rm -rf "$d" "/run/circus-daemons/${d##*/circus-daemon-}"',
                "done",
            ]
        )
    else:
        lines.extend(
            [
                "for d in /run/service/circus-daemon-*; do",
                '    [ -d "$d" ] || continue',
                '    /command/s6-svc -wD -T 12000 -d "$d" || true',
                '    rm -rf "$d" "/run/circus-daemons/${d##*/circus-daemon-}"',
                "done",
            ]
        )
    lines.append("/command/s6-svscanctl -an /run/service")
    return "\n".join(lines) + "\n"


#: How long a stop waits for a daemon to go down, in milliseconds.
STOP_WAIT_MS = KILL_TIMEOUT_MS + 5000


def _require_registered(name: str) -> list[str]:
    """Return the shell lines that guard a control action on a daemon.

    The lines abort with exit code 4 when the daemon has no service
    directory in the sandbox, i.e. when it is not registered.

    :param name: Daemon name.
    :returns: Shell lines checking for the service directory.
    """
    s = service_dir(name)
    return [
        f"s={s}",
        'if [ ! -d "$s" ]; then',
        f'    echo "daemon {name} is not registered in this sandbox" >&2',
        "    exit 4",
        "fi",
    ]


def build_start_script(name: str) -> str:
    """Render a script that starts a registered daemon.

    The script clears the ``exits`` and ``failed`` markers, then tells s6
    to bring the service up.

    :param name: Daemon name.
    :returns: The complete start script text with a final newline.
    """
    sd = secret_dir(name)
    lines = _require_registered(name)
    lines.extend(
        [
            f"rm -f {sd}/exits {sd}/failed",
            '/command/s6-svc -u "$s"',
        ]
    )
    return "\n".join(lines) + "\n"


def build_stop_script(name: str) -> str:
    """Render a script that stops a registered daemon.

    The script sends SIGTERM via s6 and waits until the service is down
    and its finish script ran, up to :data:`STOP_WAIT_MS` milliseconds.

    :param name: Daemon name.
    :returns: The complete stop script text with a final newline.
    """
    lines = _require_registered(name)
    lines.append(f'/command/s6-svc -wD -T {STOP_WAIT_MS} -d "$s"')
    return "\n".join(lines) + "\n"


def build_restart_script(name: str) -> str:
    """Render a script that restarts a registered daemon.

    The script stops the daemon (ignoring failure), clears the ``exits``
    and ``failed`` markers and starts the service again.

    :param name: Daemon name.
    :returns: The complete restart script text with a final newline.
    """
    sd = secret_dir(name)
    lines = _require_registered(name)
    lines.extend(
        [
            f'/command/s6-svc -wD -T {STOP_WAIT_MS} -d "$s" || true',
            f"rm -f {sd}/exits {sd}/failed",
            '/command/s6-svc -u "$s"',
        ]
    )
    return "\n".join(lines) + "\n"


def build_stop_all_script() -> str:
    """Render a script that stops every daemon in the sandbox.

    All services are signalled in parallel and the script waits for them
    to go down.

    :returns: The complete stop-all script text with a final newline.
    """
    return f"""for d in {S6_SCANDIR}/{SERVICE_PREFIX}*; do
    [ -d "$d" ] || continue
    /command/s6-svc -wD -T {STOP_WAIT_MS} -d "$d" &
done
wait
"""


def build_status_script() -> str:
    """Render a script that reports the state of every daemon.

    For each daemon service directory the script prints one line with the
    daemon name, the ``failed`` marker flag (1 or 0) and the
    ``s6-svstat`` fields ``up``, ``wantedup``, ``pid`` and ``updownfor``.

    :returns: The complete status script text with a final newline.
    """
    return f"""for d in {S6_SCANDIR}/{SERVICE_PREFIX}*; do
    [ -d "$d" ] || continue
    n=${{d##*/{SERVICE_PREFIX}}}
    f=0
    [ -e "{SECRET_ROOT}/$n/failed" ] && f=1
    st=$(/command/s6-svstat -o up,wantedup,pid,updownfor "$d" 2>/dev/null) || st=unknown
    echo "$n $f $st"
done
"""


def build_port_wait_script(port: int, timeout_seconds: int) -> str:
    """Render a script that waits until a guest TCP port accepts a connection.

    The script probes the port once per second with ``socat`` and exits 0
    on the first successful connect, or 1 after ``timeout_seconds``
    failed probes.

    :param port: TCP port to probe on 127.0.0.1 inside the guest.
    :param timeout_seconds: How many seconds to keep probing.
    :returns: The complete port wait script text with a final newline.
    """
    return f"""i=0
while [ "$i" -lt {timeout_seconds} ]; do
    if socat -u OPEN:/dev/null TCP:127.0.0.1:{port},connect-timeout=1 >/dev/null 2>&1; then
        exit 0
    fi
    sleep 1
    i=$((i + 1))
done
exit 1
"""


def build_logs_command(name: str, lines: int, follow: bool) -> list[str]:
    """Return the host command that tails a daemon's log.

    The command is meant to run inside the guest (e.g. via
    ``msb exec <sandbox>``).

    :param name: Daemon name.
    :param lines: Number of trailing lines to print.
    :param follow: Whether to keep following the log file.
    :returns: The argument list for ``tail``.
    """
    cmd = ["tail", "-n", str(lines), "-F", f"{log_dir(name)}/current"]
    if not follow:
        cmd.remove("-F")
    return cmd


@dataclass(frozen=True)
class DaemonStatus:
    """State of one registered daemon, from the status script.

    :ivar name: Daemon name.
    :ivar state: One of "running", "stopping", "starting", "stopped",
        "failed" or "unknown".
    :ivar pid: Process ID while up, else None.
    :ivar seconds: Seconds in the current up/down state, if known.
    """

    name: str
    state: str
    pid: int | None
    seconds: int | None


def parse_status_output(text: str) -> dict[str, DaemonStatus]:
    """Parse the output of :func:`build_status_script`.

    Each non-empty line holds ``name`` and the ``failed`` flag followed by
    the four ``s6-svstat`` fields (or fewer fields when the state could
    not be read).  Lines with fewer than three fields are skipped.

    :param text: Raw script output.
    :returns: Mapping of daemon name to its parsed status.
    """
    statuses: dict[str, DaemonStatus] = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        name = parts[0]
        failed = parts[1] == "1"
        rest = parts[2:]
        if len(rest) < 4:
            statuses[name] = DaemonStatus(name, "unknown", None, None)
            continue
        up = rest[0] == "true"
        wanted = rest[1] == "true"
        try:
            pid_val = int(rest[2])
        except ValueError:
            pid_val = 0
        try:
            seconds = int(rest[3])
        except ValueError:
            seconds = None
        pid: int | None = pid_val if pid_val > 0 else None
        if up and wanted:
            state = "running"
        elif up and not wanted:
            state = "stopping"
        elif not up and failed:
            state = "failed"
        elif not up and wanted:
            state = "starting"
        else:
            state = "stopped"
        statuses[name] = DaemonStatus(name, state, pid, seconds)
    return statuses


def format_duration(seconds: int | None) -> str:
    """Format a duration in seconds as a compact human string.

    :param seconds: Number of seconds, or None.
    :returns: ``"-"`` for None, else the largest fitting unit with its
        whole count, e.g. ``45`` -> ``"45s"`` and ``3600`` -> ``"1h"``.
    """
    if seconds is None:
        return "-"
    if seconds < 60:
        return f"{seconds}s"
    if seconds < 3600:
        return f"{seconds // 60}m"
    if seconds < 86400:
        return f"{seconds // 3600}h"
    return f"{seconds // 86400}d"
